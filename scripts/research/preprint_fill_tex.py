"""Write the preprint tables from preprint_all/preprint_extra/preprint_tso_gap outputs into the tex: Table live (rows,
tso references), elo_live.dat (and the Elo axis range), Table cov (covpairs.csv), Table tsogap (tso_gap.json), and
params.dat (late_field_2026-10-16.json). usage: python preprint_fill_tex.py OUTDIR docs/preprint/energybench_methodology.tex LAST
Prose numbers are not touched: update them by hand from the same outputs."""
import json, sys, os, re
import numpy as np, pandas as pd
d, tex, LAST = sys.argv[1], sys.argv[2], sys.argv[3]
T = open(tex).read(); D = os.path.dirname(os.path.abspath(tex))
COV = lambda m: m.endswith("_cov") or m in ("lgbm_cov", "lin_cov", "lin_cov_2y", "lgbm_prod", "ens_hybrid", "ens_fm_cov")
f3 = lambda v: "--" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.3f}"
nm = lambda m: (rf"\texttt{{\textbf{{{m.replace('_', chr(92)+'_')}}}}}" if COV(m) else rf"\texttt{{{m.replace('_', chr(92)+'_')}}}")
st = json.load(open(f"{d}/standings.json"))
rows = [m for m in sorted(st, key=lambda m: -st[m].get("elo", 0)) if "elo" in st[m] and st[m]["races"] >= 100]
L = [f"% rows generated by scripts/research/preprint_all.py (as-run scores, issue days up to {LAST})"]
for i, m in enumerate(rows, 1):
    v = st[m]; L.append(f"    {i} & {nm(m)} & {v['elo']:.0f} & [{v['lo']:.0f}, {v['hi']:.0f}] & {v['races']} & {f3(v['rel'])} & {f3(v['relr'])} & " + " & ".join(f3(v.get(t)) for t in ["price", "wind", "solar", "load"]) + r" \\")
v = st["tso_cutoff"]
p = pd.read_csv(f"{d}/perseries.csv"); gm = lambda a: float(np.exp(np.mean(np.log(a))))
t = p[(p.model == "tso_final") & ~p.zone.isin(["DK1", "DK2"])]
L += [r"    \midrule", r"    \multicolumn{11}{@{}l}{\emph{References: the grid operators' forecasts (Section~\ref{sec:tso})}} \\",
      f"    -- & \\texttt{{tso\\_cutoff}} & -- & -- & {v['races']} & {f3(v['rel'])} & {f3(v['relr'])} & -- & {f3(v['wind'])} & {f3(v['solar'])} & {f3(v['load'])} \\\\",
      f"    -- & \\texttt{{tso\\_final}} & -- & -- & -- & {gm(t.rel):.3f} & {gm(t.relr):.3f} & -- & {gm(t[t.target=='wind'].rel):.3f} & {gm(t[t.target=='solar'].rel):.3f} & -- \\\\"]
a = T.index("% rows generated by scripts/research/preprint_all.py"); b = T.index(r"\bottomrule", a)
T = T[:a] + "\n".join(L) + "\n" + T[b:]
with open(f"{D}/elo_live.dat", "w") as o:
    o.write("y elo lo hi cov label\n")
    for y, m in enumerate(reversed(rows)):
        v = st[m]; o.write(f"{y} {v['elo']:.1f} {v['elo']-v['lo']:.1f} {v['hi']-v['elo']:.1f} {1 if COV(m) else 0} {m.replace('_', chr(92)+'_')}\n")
n = len(rows)
T = re.sub(r"ymax=\d+\.7,\n  ytick=\{0,\.\.\.,\d+\}", f"ymax={n-0.3:.1f},\n  ytick={{0,...,{n-1}}}", T)
# covariate table
cp = pd.read_csv(f"{d}/covpairs.csv").set_index("model")
NAME = {"chronos2": ("Chronos-2", "native"), "timesfm3": ("TimesFM 3.0", "native"), "t0_alpha": ("t0-alpha", "native"), "t0_beta": ("t0-beta", "native"),
        "t0_gamma": ("t0-gamma", "native"), "tirex2": ("TiRex-2", "native"), "timestral": ("Timestral", "native"),
        "timesfm25": ("TimesFM 2.5", "ridge"), "tabby": ("Tabby", "ridge"), "tabby_pretrain": ("Tabby-Pretrain", "ridge")}
pc = lambda x: f"${'+' if round(100*x) >= 0 else '-'}{abs(round(100*x)):.0f}\\%$"
L = []
for m, (lab, kind) in NAME.items():
    if kind == "ridge" and m == "timesfm25": L.append(r"\midrule")
    r = cp.loc[m]
    L.append(f"{lab} & {kind} & {int(r.days)} & {int(r.races)} & {r.rel:.3f} & {r.rel_cov:.3f} & " + " & ".join(pc(r[k]) for k in ["all", "price", "wind", "solar", "load"]) + r" \\")
a = T.index(r"\label{tab:cov}"); a = T.index(r"\midrule", a) + len(r"\midrule") + 1; b = T.index(r"\bottomrule", a)
T = T[:a] + "\n".join(L) + "\n" + T[b:]
# tso gap table
g = json.load(open(f"{d}/tso_gap.json"))
LAB = {"timesfm25_cov": "TimesFM 2.5", "chronos2_cov": "Chronos-2", "t0_alpha_cov": "t0-alpha", "tirex2_cov": "TiRex-2", "timesfm3_cov": "TimesFM 3.0",
       "tabby_cov": "Tabby", "t0_beta_cov": "t0-beta", "t0_gamma_cov": "t0-gamma", "timestral_cov": "Timestral"}
sg = lambda x: f"${'+' if round(x) > 0 else ('-' if round(x) < 0 else '')}{abs(round(x)):.0f}$"
pg = lambda x: f"${'+' if round(x) > 0 else ('-' if round(x) < 0 else '')}{abs(round(x)):.0f}\\%$"
fm = sorted(LAB, key=lambda m: g["models"][m]["all"][0])
L = [f"{LAB[m]} & {pg(g['models'][m]['all'][0])} & [{sg(g['models'][m]['all'][1])}, {sg(g['models'][m]['all'][2])}] & {pg(g['models'][m]['wind_solar'][0])} & {pg(g['models'][m]['load'][0])} \\\\" for m in fm]
m = "lgbm_prod"; L += [r"\midrule", f"\\m{{lgbm\\_prod}} & {pg(g['models'][m]['all'][0])} & [{sg(g['models'][m]['all'][1])}, {sg(g['models'][m]['all'][2])}] & {pg(g['models'][m]['wind_solar'][0])} & {pg(g['models'][m]['load'][0])} \\\\"]
a = T.index(r"\label{tab:tsogap}"); a = T.index(r"\midrule", a) + len(r"\midrule") + 1; b = T.index(r"\bottomrule", a)
T = T[:a] + "\n".join(L) + "\n" + T[b:]
open(tex, "w").write(T)
# params.dat from the 16 Oct window
lf = json.load(open(f"{d}/late_field_2026-10-16.json"))
old = pd.read_csv(f"{D}/params.dat", sep=" ")
old["hist"] = [round(lf[m]["rel"], 3) for m in old.model]
old["cov"] = [round(lf[m + "_cov"]["rel"], 3) if m + "_cov" in lf else float("nan") for m in old.model]
old.to_csv(f"{D}/params.dat", sep=" ", index=False, na_rep="nan")
print(n, "ranked; gap races", g["races"], g["days"], g["first"], g["last"])
